import { test, expect, type Page } from '@playwright/test';
const navigate = (page: Page, name: string) => page.viewportSize()!.width < 768
  ? page.getByRole('navigation', {name:'하단 탭'}).getByRole('button',{name,exact:true}).click()
  : page.getByRole('navigation', {name:'메인 메뉴'}).getByRole('button',{name:new RegExp(`^${name}`)}).click();
async function record(page: Page, type: string, amount: string, memo: string) {
  await page.getByRole('button',{name:'기록하기',exact:true}).click();
  const dialog = page.getByRole('dialog',{name:'가계부 기록하기'});
  await dialog.getByLabel('구분',{exact:true}).selectOption(type);
  await dialog.getByLabel('금액 (원)',{exact:true}).fill(amount);
  await dialog.getByLabel('메모').fill(memo);
  await dialog.getByRole('button',{name:'기록 저장',exact:true}).click();
  await expect(dialog).not.toBeVisible();
}
test('ledger views, rewards, persistence, deletion and monthly reports',async ({page}, testInfo)=>{
  const errors: string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await navigate(page,'캘린더');
  await page.getByLabel('선택 날짜',{exact:true}).fill('2024-02-29');
  await expect(page.getByRole('heading',{name:'2024년 2월',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:/^2024-02-29, 수입/})).toBeVisible();
  await record(page,'EXPENSE','450000','윤년 식비');
  await expect(page.getByRole('status')).toHaveText('오늘의 가계부 기록 완료! +10 XP 획득!');
  await record(page,'INCOME','3000000','월급');
  await expect(page.getByRole('status')).toHaveText('가계부 기록을 저장했어요.');
  await record(page,'SAVING','500000','적금');
  const state = await page.evaluate(()=>JSON.parse(localStorage.getItem('rich-grandma-tycoon-v1')!).state);
  expect(state.character.currentXp).toBe(10);
  expect(state.transactions).toHaveLength(3);
  expect(state.xpLogs).toHaveLength(1);
  await page.getByRole('button',{name:'일간 Daily',exact:true}).click();
  const list = page.getByRole('list');
  await expect(list.getByText('+3,000,000원',{exact:true})).toHaveClass(/text-blue-600/);
  await expect(list.getByText('-450,000원',{exact:true})).toHaveClass(/text-rose-500/);
  await expect(list.getByText('500,000원',{exact:true})).toHaveClass(/text-indigo-600/);
  await page.getByRole('button',{name:'윤년 식비 -450,000원 삭제',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'삭제하기'}).click();
  await expect(list.getByText('윤년 식비')).toHaveCount(0);
  await record(page,'EXPENSE','450000','다시 입력');
  await expect(page.getByRole('status')).toHaveText('가계부 기록을 저장했어요.');
  await page.reload();
  await navigate(page,'캘린더');
  await page.getByLabel('선택 날짜',{exact:true}).fill('2024-02-29');
  await expect(page.getByText('다시 입력',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('rich-grandma-tycoon-v1')!).state.character.currentXp)).toBe(10);
  await page.screenshot({path:testInfo.outputPath('calendar.png'),fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'주간 Weekly',exact:true}).click();
  await page.getByLabel('선택 날짜',{exact:true}).fill('2025-12-31');
  await expect(page.getByRole('heading',{name:'2025-12-28 ~ 2026-01-03',exact:true})).toBeVisible();
  await expect(page.locator('main article')).toHaveCount(7);
  await navigate(page,'통계');
  await page.getByLabel('통계 기준 월',{exact:true}).fill('2024-02');
  await expect(page.locator('article').filter({hasText:'총수입'})).toContainText('+3,000,000원');
  await expect(page.locator('article').filter({hasText:'총지출'})).toContainText('-450,000원');
  await expect(page.locator('article').filter({hasText:'총저축'})).toContainText('500,000원');
  const progress = page.getByRole('progressbar',{name:'식비 예산 사용률'});
  await expect(progress).toHaveAttribute('aria-valuenow','100');
  await expect(progress.locator('div')).toHaveClass(/bg-rose-500/);
  await expect(page.getByText('50,000원 초과',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('statistics.png'),fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'다음 달',exact:true}).click();
  await expect(page.getByText('이 달에는 아직 기록이 없어요.',{exact:false})).toBeVisible();
  await expect(progress).toHaveAttribute('aria-valuenow','0');
  expect(errors).toEqual([]);
});
